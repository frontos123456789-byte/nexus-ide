const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
const cmdName = (s: string) => s.replace(/^\//, "").toLowerCase().replace(/[^a-z0-9_]/g, "").slice(0, 32);

export function botCommands(c: BotConfig): BotCommand[] {
  const base = BOT_TEMPLATES.find((t) => t.id === c.template)?.commands ?? [];
  const seen = new Set<string>();
  return [...base, ...c.commands]
    .map((x) => ({ ...x, command: cmdName(x.command) }))
    .filter((x) => x.command && !["start", "help"].includes(x.command) && !seen.has(x.command) && seen.add(x.command));
}

function effectiveDb(c: BotConfig): BotDb {
  const t = BOT_TEMPLATES.find((x) => x.id === c.template);
  return c.db === "none" && t?.needsDb ? "sqlite" : c.db;
}

