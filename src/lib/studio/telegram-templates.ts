function nodeDb(db: BotDb): string {
  if (db === "postgres")
    return `import pg from "pg";

const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const ready = (async () => {
  await pool.query("CREATE TABLE IF NOT EXISTS users (id BIGINT PRIMARY KEY, name TEXT, subscribed BOOLEAN DEFAULT FALSE)");
  await pool.query("CREATE TABLE IF NOT EXISTS notes (id SERIAL PRIMARY KEY, user_id BIGINT, text TEXT)");
  await pool.query("CREATE TABLE IF NOT EXISTS tickets (id SERIAL PRIMARY KEY, user_id BIGINT, text TEXT)");
})();
const q = async (sql, params) => { await ready; return pool.query(sql, params); };

export const saveUser = (u) => q("INSERT INTO users (id, name) VALUES ($1, $2) ON CONFLICT (id) DO UPDATE SET name = $2", [u.id, u.first_name]);
export const setSubscribed = (id, v) => q("UPDATE users SET subscribed = $2 WHERE id = $1", [id, v]);
export const subscribers = async () => (await q("SELECT id FROM users WHERE subscribed")).rows.map((r) => Number(r.id));
export const addNote = (id, text) => q("INSERT INTO notes (user_id, text) VALUES ($1, $2)", [id, text]);
export const listNotes = async (id) => (await q("SELECT text FROM notes WHERE user_id = $1 ORDER BY id", [id])).rows.map((r) => r.text);
export const addTicket = async (id, text) => (await q("INSERT INTO tickets (user_id, text) VALUES ($1, $2) RETURNING id", [id, text])).rows[0].id;
export const ticketUser = async (tid) => (await q("SELECT user_id FROM tickets WHERE id = $1", [tid])).rows[0]?.user_id;
`;
  return `import Database from "better-sqlite3";

const d = new Database(process.env.DB_PATH ?? "bot.db");
d.exec("CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, name TEXT, subscribed INTEGER DEFAULT 0); CREATE TABLE IF NOT EXISTS notes (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, text TEXT); CREATE TABLE IF NOT EXISTS tickets (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, text TEXT)");

export const saveUser = async (u) => d.prepare("INSERT INTO users (id, name) VALUES (?, ?) ON CONFLICT(id) DO UPDATE SET name = excluded.name").run(u.id, u.first_name);
export const setSubscribed = async (id, v) => d.prepare("UPDATE users SET subscribed = ? WHERE id = ?").run(v ? 1 : 0, id);
export const subscribers = async () => d.prepare("SELECT id FROM users WHERE subscribed = 1").all().map((r) => r.id);
export const addNote = async (id, text) => d.prepare("INSERT INTO notes (user_id, text) VALUES (?, ?)").run(id, text);
export const listNotes = async (id) => d.prepare("SELECT text FROM notes WHERE user_id = ? ORDER BY id").all(id).map((r) => r.text);
export const addTicket = async (id, text) => d.prepare("INSERT INTO tickets (user_id, text) VALUES (?, ?)").run(id, text).lastInsertRowid;
export const ticketUser = async (tid) => d.prepare("SELECT user_id FROM tickets WHERE id = ?").get(tid)?.user_id;
`;
}

