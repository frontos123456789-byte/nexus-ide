function pyDb(db: BotDb, t: BotTemplateId): string {
  if (db === "postgres")
    return `"""PostgreSQL storage (asyncpg). Set DATABASE_URL."""
import os

import asyncpg

_pool = None


async def pool():
    global _pool
    if _pool is None:
        _pool = await asyncpg.create_pool(os.environ["DATABASE_URL"])
        async with _pool.acquire() as c:
            await c.execute("CREATE TABLE IF NOT EXISTS users (id BIGINT PRIMARY KEY, name TEXT, subscribed BOOLEAN DEFAULT FALSE)")
            await c.execute("CREATE TABLE IF NOT EXISTS notes (id SERIAL PRIMARY KEY, user_id BIGINT, text TEXT)")
            await c.execute("CREATE TABLE IF NOT EXISTS tickets (id SERIAL PRIMARY KEY, user_id BIGINT, text TEXT)")
    return _pool


async def save_user(u):
    p = await pool()
    await p.execute("INSERT INTO users (id, name) VALUES ($1, $2) ON CONFLICT (id) DO UPDATE SET name = $2", u.id, u.full_name)


async def set_subscribed(uid, value):
    p = await pool()
    await p.execute("UPDATE users SET subscribed = $2 WHERE id = $1", uid, value)


async def subscribers():
    p = await pool()
    return [r["id"] for r in await p.fetch("SELECT id FROM users WHERE subscribed")]


async def add_note(uid, text):
    p = await pool()
    await p.execute("INSERT INTO notes (user_id, text) VALUES ($1, $2)", uid, text)


async def list_notes(uid):
    p = await pool()
    return [r["text"] for r in await p.fetch("SELECT text FROM notes WHERE user_id = $1 ORDER BY id", uid)]


async def add_ticket(uid, text):
    p = await pool()
    return await p.fetchval("INSERT INTO tickets (user_id, text) VALUES ($1, $2) RETURNING id", uid, text)


async def ticket_user(tid):
    p = await pool()
    return await p.fetchval("SELECT user_id FROM tickets WHERE id = $1", tid)
`;
  void t;
  return `"""SQLite storage (stdlib). File path: DB_PATH (default bot.db)."""
import os
import sqlite3

PATH = os.getenv("DB_PATH", "bot.db")


def _conn():
    c = sqlite3.connect(PATH)
    c.execute("CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, name TEXT, subscribed INTEGER DEFAULT 0)")
    c.execute("CREATE TABLE IF NOT EXISTS notes (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, text TEXT)")
    c.execute("CREATE TABLE IF NOT EXISTS tickets (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, text TEXT)")
    return c


async def save_user(u):
    with _conn() as c:
        c.execute("INSERT INTO users (id, name) VALUES (?, ?) ON CONFLICT(id) DO UPDATE SET name = excluded.name", (u.id, u.full_name))


async def set_subscribed(uid, value):
    with _conn() as c:
        c.execute("UPDATE users SET subscribed = ? WHERE id = ?", (1 if value else 0, uid))


async def subscribers():
    with _conn() as c:
        return [r[0] for r in c.execute("SELECT id FROM users WHERE subscribed = 1")]


async def add_note(uid, text):
    with _conn() as c:
        c.execute("INSERT INTO notes (user_id, text) VALUES (?, ?)", (uid, text))


async def list_notes(uid):
    with _conn() as c:
        return [r[0] for r in c.execute("SELECT text FROM notes WHERE user_id = ? ORDER BY id", (uid,))]


async def add_ticket(uid, text):
    with _conn() as c:
        return c.execute("INSERT INTO tickets (user_id, text) VALUES (?, ?)", (uid, text)).lastrowid


async def ticket_user(tid):
    with _conn() as c:
        row = c.execute("SELECT user_id FROM tickets WHERE id = ?", (tid,)).fetchone()
        return row[0] if row else None
`;
}

